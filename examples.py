"""Generates docs/DECISION_EXAMPLES.md from REAL runs (so the examples can never drift from the code)."""
import json
from wfp.app import build_engine

e = build_engine(":memory:", sleep=lambda s: None)
base = json.load(open("samples/vendor_good.json"))
cases = [
    ("1. Approved (happy path)", base),
    ("2. Rejected by a mandatory rule", {**base, "has_insurance": False, "tax_id": "NOINSUR1234"}),
    ("3. Rejected by sanctions dependency result", {**base, "country": "KP", "tax_id": "SANCTION123"}),
    ("4. Manual review after conditional branch (high exposure)", {**base, "requested_credit_limit": 200000, "years_in_business": 2, "annual_revenue": 300000, "tax_id": "HIGHEXP12345"}),
]
out = ["# Decision Explanation Examples", "", "_Generated by `python examples.py` from real engine runs._", ""]
for title, payload in cases:
    req, _ = e.submit("vendor_approval", payload)
    ex = e.explain(req["id"])
    out += [f"## {title}", "", "**Input**", "```json", json.dumps(payload, indent=2), "```",
            f"**Result:** `{ex['status']}`  |  **Stage path:** `{' -> '.join(ex['stage_path'])}`", "",
            "**Rules evaluated (rule trace with data reference)**", "",
            "| Rule | Result | Field (data reference) | Operator | Expected | Observed |", "|---|---|---|---|---|---|"]
    for r in ex["rules_evaluated"]:
        for c in r["conditions"]:
            out.append(f"| {r['rule_id']} | {r['result']} | `{c['field']}` | {c['op']} | {c['expected']} | {c['observed']} |")
    out += ["", "**Reasoning**", ""] + [f"- {l}" for l in ex["reasoning"]] + [""]

# retry flow example
req, _ = e.submit("vendor_approval", {**base, "vendor_name": "Flaky RETRYME Ltd", "tax_id": "FLAKY1234567"})
out += ["## 5. Dependency failure -> PENDING_RETRY -> retry -> approved", "",
        f"After first submit: `{req['status']}` at stage `{req['current_stage']}`", ""]
req = e.retry(req["id"])
out += [f"After `retry`: `{req['status']}`", "", "**History (full change log)**", "", "| From | To | Stage | Note |", "|---|---|---|---|"]
for h in e.store.history(req["id"]):
    out.append(f"| {h['from_status']} | {h['to_status']} | {h['stage']} | {h['note']} |")
out += ["", "**Audit excerpt (dependency attempts)**", ""]
for a in e.store.audit(req["id"]):
    if a["kind"] in ("DEPENDENCY", "DECISION"):
        out.append(f"- seq {a['seq']} `{a['kind']}`: {a['message']}")
open("docs/DECISION_EXAMPLES.md", "w").write("\n".join(out) + "\n")
print("written")
